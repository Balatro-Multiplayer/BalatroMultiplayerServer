// Bundles src/ into the single modules/index.js that Nakama's JavaScript
// runtime loads (nakama/local.yml: runtime.js_entrypoint).
//
// Nakama finds InitModule, and every hook/RPC/match handler it registers, by
// name in the script's global scope, so the output must stay a plain script:
// ESM format with no exports keeps every function declaration at top level,
// and minification stays off so the names survive.
// `--watch` (compose.local.yml's nakama-bundle service) rebuilds on every
// change under src/ and keeps running.
import { build, context } from 'esbuild'

const HEADER = `// GENERATED by nakama/build.mjs from nakama/src -- do not edit; run
// \`pnpm --filter bmp-nakama-modules build\` after changing src/.`

const options = {
	entryPoints: ['src/main.ts'],
	outfile: 'modules/index.js',
	bundle: true,
	format: 'esm',
	target: 'es2015',
	minify: false,
	treeShaking: true,
	banner: { js: HEADER },
	logLevel: 'info',
}

if (process.argv.includes('--watch')) {
	const ctx = await context(options)
	await ctx.watch()
} else {
	await build(options)
}
